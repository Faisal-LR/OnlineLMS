
-- Online Learning Management System
-- DDL: Create the database tables

CREATE TABLE APP_USERS (
    USER_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FULL_NAME VARCHAR2(100) NOT NULL,
    EMAIL VARCHAR2(100) UNIQUE NOT NULL,
    PASSWORD_HASH VARCHAR2(255) NOT NULL,
    USER_ROLE VARCHAR2(20) DEFAULT 'STUDENT'
        CHECK (USER_ROLE IN ('STUDENT', 'INSTRUCTOR', 'ADMIN'))
);

CREATE TABLE COURSES (
    COURSE_ID NUMBER PRIMARY KEY,
    COURSE_NAME VARCHAR2(150) NOT NULL,
    DESCRIPTION VARCHAR2(500),
    INSTRUCTOR VARCHAR2(100),
    DURATION_HOURS NUMBER,
    STATUS VARCHAR2(20) DEFAULT 'ACTIVE'
        CHECK (STATUS IN ('ACTIVE', 'INACTIVE'))
);

CREATE TABLE ENROLLMENTS (
    ENROLLMENT_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USER_ID NUMBER NOT NULL,
    COURSE_ID NUMBER NOT NULL,
    PROGRESS NUMBER DEFAULT 0 CHECK (PROGRESS BETWEEN 0 AND 100),
    ENROLLMENT_DATE DATE DEFAULT SYSDATE,
    CONSTRAINT FK_ENROLL_USER FOREIGN KEY (USER_ID)
        REFERENCES APP_USERS(USER_ID),
    CONSTRAINT FK_ENROLL_COURSE FOREIGN KEY (COURSE_ID)
        REFERENCES COURSES(COURSE_ID),
    CONSTRAINT UQ_USER_COURSE UNIQUE (USER_ID, COURSE_ID)
);

CREATE TABLE QUIZZES (
    QUIZ_ID NUMBER PRIMARY KEY,
    COURSE_ID NUMBER NOT NULL,
    QUIZ_TITLE VARCHAR2(150) NOT NULL,
    TOTAL_MARKS NUMBER NOT NULL,
    CONSTRAINT FK_QUIZ_COURSE FOREIGN KEY (COURSE_ID)
        REFERENCES COURSES(COURSE_ID)
);

CREATE TABLE QUIZ_ATTEMPTS (
    ATTEMPT_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    QUIZ_ID NUMBER NOT NULL,
    USER_ID NUMBER NOT NULL,
    SCORE NUMBER NOT NULL CHECK (SCORE >= 0),
    ATTEMPT_DATE DATE DEFAULT SYSDATE,
    CONSTRAINT FK_ATTEMPT_QUIZ FOREIGN KEY (QUIZ_ID)
        REFERENCES QUIZZES(QUIZ_ID),
    CONSTRAINT FK_ATTEMPT_USER FOREIGN KEY (USER_ID)
        REFERENCES APP_USERS(USER_ID)
);
